import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const files = {
  "/index.html": "public/index.html",
  "/app.css": "public/app.css",
  "/app.js": "public/app.js",
  "/input.js": "public/input.js",
  "/zoom.js": "public/zoom.js",
  "/stream.js": "public/stream.js",
  "/audio.js": "public/audio.js",
  "/capture.html": "public/capture.html",
  "/lucide.min.js": "node_modules/lucide/dist/umd/lucide.min.js",
};
const values = await Promise.all(Object.entries(files).map(async ([route, file]) => [route, await readFile(resolve(root, file), "utf8")]));
const output = `// Generated by scripts/generate-assets.mjs.\nexport const assets = ${JSON.stringify(Object.fromEntries(values))};\n`;
await mkdir(resolve(root, "src"), { recursive: true });
await writeFile(resolve(root, "src/generated-assets.js"), output);
